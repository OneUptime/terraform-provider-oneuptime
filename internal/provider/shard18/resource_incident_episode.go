// ModifyPlan finds, by email address, the people this incident episode names (see people.go),
// and keeps the state when nothing a configuration sets changes (see
// importsettle.go).
func (r *IncidentEpisodeResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
    // Destroying: nothing to plan.
    if req.Plan.Raw.IsNull() {
        return
    }

    // Under Crossplane, what a manifest leaves out is the record's (see crossplane.go).
    KeepLeftOutUnderCrossplane(ctx, req, resp)

    // What people and OneUptime both change: OneUptime's change is never one
    // to undo (see shared.go).
    PlanShared(ctx, req, resp, r.client, []SharedAttribute{
        {Name: "description", Entries: false},
        {Name: "incident_severity_id", Entries: false},
        {Name: "is_private", Entries: false},
        {Name: "labels", Entries: true},
        {Name: "on_call_duty_policies", Entries: true},
        {Name: "title", Entries: false},
    })

    PlanPersonID(ctx, r.client, req, resp, PersonAttribute{
        ID:       "assigned_to_user_id",
        Email:    "assigned_to_user_email",
        Invites:  false,
        Replaces: false,
    })

    KeepStateWhenNothingChanges(ctx, req, resp)
}

