    data.OnCallDutyPolicies, isDeclared = SetEntriesAfterWrite(r.client, isCreate, declared["on_call_duty_policies"], config.OnCallDutyPolicies, plan.OnCallDutyPolicies, data.OnCallDutyPolicies)
    declared["on_call_duty_policies"] = isDeclared
    return declared
