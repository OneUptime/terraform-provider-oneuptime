// ModifyPlan finds, by email address, the people this postmortem action item names (see people.go),
// and keeps the state when nothing a configuration sets changes (see
// importsettle.go).
func (r *PostmortemActionItemResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
    // Destroying: nothing to plan.
    if req.Plan.Raw.IsNull() {
        return
    }

    // Under Crossplane, what a manifest leaves out is the record's (see crossplane.go).
    KeepLeftOutUnderCrossplane(ctx, req, resp)

    PlanPersonID(ctx, r.client, req, resp, PersonAttribute{
        ID:       "owner_user_id",
        Email:    "owner_user_email",
        Invites:  false,
        Replaces: false,
    })

    KeepStateWhenNothingChanges(ctx, req, resp)
}

